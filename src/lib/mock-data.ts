export function calculateCoursePerformance(c: Course) {
  const isAttendanceApplicable = !c.isAttendanceNA && c.attendanceTarget > 0;
  const attendComp = isAttendanceApplicable 
    ? Math.round((c.attendanceRate / c.attendanceTarget) * 1000) / 10 
    : null;

  // Công thức Excel của Viện: =IF((Pass1st / Target) >= 1, Pass1st / Target, MIN(1, (Pass1st / Target) + ((PassResit / Target) * 1)))
  let passComp: number | null = null;
  if (!c.isPassNA && c.passTarget > 0) {
    const rawPass1st = c.passRate / c.passTarget;
    const resitRate = typeof c.passResitRate === 'number' ? c.passResitRate : 0;
    if (rawPass1st >= 1) {
      passComp = Math.round(rawPass1st * 1000) / 10;
    } else {
      const resitAdd = resitRate / c.passTarget;
      const combined = Math.min(1, rawPass1st + resitAdd);
      passComp = Math.round(combined * 1000) / 10;
    }
  }

  const isSubmitApplicable = !c.isSubmitNA && c.submitTarget > 0;
  const submitComp = isSubmitApplicable 
    ? Math.round((c.submitRate / c.submitTarget) * 1000) / 10 
    : null;

  let compSum = 0;
  let compCount = 0;
  if (attendComp !== null) { compSum += attendComp; compCount++; }
  if (passComp !== null) { compSum += passComp; compCount++; }
  if (submitComp !== null) { compSum += submitComp; compCount++; }

  const avgComp = compCount > 0 ? Math.round((compSum / compCount) * 10) / 10 : 100;

  return {
    attendComp,
    passComp,
    submitComp,
    avgComp
  };
}

export function calculateCoursesKPI(programId: string, filterSemester: 'current' | 'all' = 'current'): number {
  let filteredCourses = courses.filter(c => c.programId === programId);
  
  if (filterSemester === 'current') {
    if (programId === 'p_nam1') {
      filteredCourses = filteredCourses.filter(c => (c.semester === 'SEM SPRING' || c.semester === 'SEM FALL & SPRING' || c.semester === 'SEM 2') && !c.cohort.includes('dự kiến') && c.cohort !== 'I22 MT' && c.cohort !== 'I23 MX');
    } else if (programId === 'p_cu') {
      filteredCourses = filteredCourses.filter(c => c.cohort === 'I19 MX' && c.semester === 'SEM 2');
    } else if (programId === 'p_nhtc') {
      filteredCourses = filteredCourses.filter(c => (c.cohort === 'BScBF I19' || c.cohort === 'BScBF I18') && c.semester === 'SEM 2');
    } else if (programId === 'p_uwe') {
      filteredCourses = filteredCourses.filter(c => (c.cohort === 'I18 MT - IBM' && c.semester === 'SEM 2') || (c.cohort === 'I19 MX - IBM' && c.semester === 'SEM 1'));
    } else {
      filteredCourses = filteredCourses.filter(c => c.semester === 'SEM 2' && c.year <= 2 && !c.cohort.includes('dự kiến'));
    }
  } else {
    filteredCourses = filteredCourses.filter(c => !c.cohort.includes('dự kiến') && c.cohort !== 'I22 MT' && c.cohort !== 'I23 MX' && c.cohort !== 'I19 MT' && c.cohort !== 'I20 MX' && c.cohort !== 'I20 MT');
  }

  if (filteredCourses.length === 0) return 100;

  let totalScore = 0;
  let validCoursesCount = 0;

  for (const c of filteredCourses) {
    const perf = calculateCoursePerformance(c);
    totalScore += perf.avgComp;
    validCoursesCount++;
  }

  if (validCoursesCount === 0) return 100;
  return Math.round(totalScore / validCoursesCount);
}

export function calculateOverallKPI(userId: string, period: string): number {
  // 1. Vận hành - Operations (50%)
  const opScore = calculateOperationsKPI(userId, period);
  
  // 2. HĐ hỗ trợ học tập - Academic Support (20%)
  // Shared KPI: Linked directly to op5_as (Hoạt động ngoại khóa - Học tập) or fallback to op1
  const snapshots = getKPISnapshotsByUser(userId, period);
  const op5AsSnap = snapshots.find(s => s.kpiDefinitionId === 'op5_as') || snapshots.find(s => s.kpiDefinitionId === 'op1');
  const asScore = op5AsSnap ? op5AsSnap.score : 0;

  // 3. Kết quả học tập & Kỷ luật - Student Results (20%)
  // Find which program this user manages
  const userProg = programs.find(p => p.managerId === userId || p.secondaryManagerId === userId);
  const studentResultsScore = userProg ? calculateCoursesKPI(userProg.id, 'current') : 100;

  // 4. Các hoạt động khác - Other Activities (10%)
  const otherSnaps = snapshots.filter(s => {
    const def = kpiDefinitions.find(d => d.id === s.kpiDefinitionId);
    return def?.groupId === 'other_activities';
  });
  const otherScore = otherSnaps.length > 0 
    ? otherSnaps.reduce((sum, s) => sum + s.score, 0) / otherSnaps.length 
    : 0;

  // Final Overall formula
  const final = (opScore * 0.5) + (asScore * 0.2) + (studentResultsScore * 0.2) + (otherScore * 0.1);
  return Math.round(final);
}

