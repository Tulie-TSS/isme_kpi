export function createCourseEditRequest(req: Omit<CourseEditRequest, 'id' | 'status' | 'requestedAt' | 'reviewedBy' | 'reviewedAt' | 'reviewNote'>) {
  const newReq: CourseEditRequest = {
    ...req,
    id: 'cer' + Date.now(),
    status: 'pending',
    requestedAt: new Date().toISOString().replace('T', ' ').substring(0, 19),
    reviewedBy: null,
    reviewedAt: null,
    reviewNote: ''
  };
  _courseEditRequests = [newReq, ..._courseEditRequests];
  
  const course = courses.find(c => c.id === req.courseId);
  const oldValDisplay = req.oldValue === 'N/A' ? 'N/A' : typeof req.oldValue === 'number' && req.field !== 'numLecturers' && req.field !== 'numStudents' ? `${req.oldValue}%` : req.oldValue;
  const newValDisplay = req.newValue === 'N/A' ? 'N/A' : typeof req.newValue === 'number' && req.field !== 'numLecturers' && req.field !== 'numStudents' ? `${req.newValue}%` : req.newValue;
  addAuditLog(req.userId, 'Gửi yêu cầu sửa Điểm môn học', `Đã gửi yêu cầu sửa môn ${course?.name} (${req.fieldLabel}). Giá trị thay đổi: ${oldValDisplay} -> ${newValDisplay}. Lý do: "${req.reason}"`);
  
  _notifyCourseEdit();
  return newReq;
}

export function approveCourseEditRequest(id: string, reviewerId: string, note: string) {
  _courseEditRequests = _courseEditRequests.map(r => {
    if (r.id !== id) return r;
    
    // Apply changes to course object
    let updates: Partial<Course> = {};
    if (r.field === 'numLecturers' || r.field === 'numStudents') {
      updates[r.field] = typeof r.newValue === 'number' ? r.newValue : parseInt(String(r.newValue), 10) || 0;
    } else if (r.isNA || r.newValue === 'N/A') {
      if (r.field === 'attendanceRate') updates.isAttendanceNA = true;
      if (r.field === 'passRate') updates.isPassNA = true;
      if (r.field === 'passResitRate') updates.isPassResitNA = true;
      if (r.field === 'submitRate') updates.isSubmitNA = true;
    } else {
      const num = typeof r.newValue === 'number' ? r.newValue : parseFloat(String(r.newValue)) || 0;
      const valDecimal = num / 100;
      updates[r.field] = valDecimal;
      if (r.field === 'attendanceRate') updates.isAttendanceNA = false;
      if (r.field === 'passRate') updates.isPassNA = false;
      if (r.field === 'passResitRate') updates.isPassResitNA = false;
      if (r.field === 'submitRate') updates.isSubmitNA = false;
    }

    updateCourseValue(r.courseId, updates);

    const course = courses.find(c => c.id === r.courseId);
    addAuditLog(reviewerId, 'Duyệt yêu cầu sửa Điểm môn học', `Đã duyệt yêu cầu sửa môn ${course?.name} của ${getUserById(r.userId)?.name}. Nội dung duyệt: "${note}"`);
    
    return {
      ...r,
      status: 'approved' as const,
      reviewedBy: reviewerId,
      reviewedAt: new Date().toISOString().replace('T', ' ').substring(0, 19),
      reviewNote: note
    };
  });
  _notifyCourseEdit();
}

export function rejectCourseEditRequest(id: string, reviewerId: string, note: string) {
  _courseEditRequests = _courseEditRequests.map(r => {
    if (r.id !== id) return r;
    
    const course = courses.find(c => c.id === r.courseId);
    addAuditLog(reviewerId, 'Từ chối yêu cầu sửa Điểm môn học', `Đã từ chối yêu cầu sửa điểm môn ${course?.name} của ${getUserById(r.userId)?.name}. Lý do từ chối: "${note}"`);
    
    return {
      ...r,
      status: 'rejected' as const,
      reviewedBy: reviewerId,
      reviewedAt: new Date().toISOString().replace('T', ' ').substring(0, 19),
      reviewNote: note
    };
  });
  _notifyCourseEdit();
}

